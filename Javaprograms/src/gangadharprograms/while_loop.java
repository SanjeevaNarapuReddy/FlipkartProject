package gangadharprograms;

public class while_loop {

	public static void main(String[] args) {
		
		{
			int i=60;
			while(i>=30)
			{
				System.out.print(i+" ");
				i--;
			}
		}
		{
			int i=-20;
			while(i>=-40)
			{
				System.out.print(i+" ");
				i--;
			}
		}
		{
			int i=-32;
			while(i<=-22)
			{
				System.out.print(i+" ");
				i++;
				}
		}
	}
	
}


